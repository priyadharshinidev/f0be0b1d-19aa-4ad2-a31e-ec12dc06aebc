// Helper method to write test results to the output
        private void WriteTestResult(string testCase, string input, string expected, string output, bool passed)
        {
            _output.WriteLine($"Test Case: {testCase}");
            _output.WriteLine($"Status: {(passed ? "PASS" : "FAIL")}");
            _output.WriteLine($"Input:    {input}");
            _output.WriteLine($"Expected: {expected}");
            _output.WriteLine($"Output:   {output}");
        }

