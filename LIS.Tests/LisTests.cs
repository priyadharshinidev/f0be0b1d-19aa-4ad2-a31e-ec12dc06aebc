        {
            string input = "6 1 5 9 2";
            string expected = "1 5 9";
            var result = LisSolver.LongestIncreasingSubsequence(input);
            
            WriteTestResult("1", input, expected, result, result == expected);
            
            Assert.Equal(expected, result);
        }

